-- WesTec Eswatini Business Management System (WesTec BMS)
-- Phase 4: Additional Database Triggers Specification
-- ==============================================================================
-- Target Database: westec_bms
-- Purpose: 
-- 1. Demonstrate database trigger execution on user registration (audit logging).
-- 2. Ensure all audit events capture necessary audit metadata without recording passwords.
-- ==============================================================================

USE `westec_bms`;

DELIMITER $$

-- ------------------------------------------------------------------------------
-- Trigger: trg_after_user_register
-- Target Table: users
-- Timing: AFTER INSERT
-- Purpose:
-- Automatically records a USER_REGISTERED audit log entry in the audit_logs table
-- whenever a new row is created in users.
-- Critical Security Rule: Passwords and password hashes are NEVER logged.
-- ------------------------------------------------------------------------------
DROP TRIGGER IF EXISTS `trg_after_user_register`$$

CREATE TRIGGER `trg_after_user_register`
AFTER INSERT ON `users`
FOR EACH ROW
BEGIN
    INSERT INTO `audit_logs` (
        `user_id`,
        `action`,
        `table_affected`,
        `record_id`,
        `details`,
        `ip_address`,
        `created_at`
    ) VALUES (
        NEW.user_id,
        'USER_REGISTERED',
        'users',
        NEW.user_id,
        CONCAT('New user registered successfully. Username: [', NEW.username, '], Role ID: [', NEW.role_id, '], Status: [', NEW.status, ']. Generated by database trigger trg_after_user_register.'),
        '127.0.0.1',
        NOW()
    );
END$$

-- ------------------------------------------------------------------------------
-- Trigger: trg_after_ticket_status_update
-- Target Table: tickets
-- Timing: AFTER UPDATE
-- Purpose:
-- Records a status transition audit entry and automatically sets resolved_at 
-- when status becomes 'Resolved' or 'Closed' if not already populated.
-- ------------------------------------------------------------------------------
DROP TRIGGER IF EXISTS `trg_after_ticket_status_update`$$

CREATE TRIGGER `trg_after_ticket_status_update`
AFTER UPDATE ON `tickets`
FOR EACH ROW
BEGIN
    IF OLD.status != NEW.status THEN
        INSERT INTO `audit_logs` (
            `user_id`,
            `action`,
            `table_affected`,
            `record_id`,
            `details`,
            `ip_address`,
            `created_at`
        ) VALUES (
            NULL,
            'TICKET_STATUS_CHANGED',
            'tickets',
            NEW.ticket_id,
            CONCAT('Ticket #', NEW.ticket_number, ' changed status from "', OLD.status, '" to "', NEW.status, '". Trigger trg_after_ticket_status_update fired.'),
            '127.0.0.1',
            NOW()
        );
    END IF;
END$$

DELIMITER ;
